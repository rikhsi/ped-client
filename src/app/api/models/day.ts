/**
 * День недели
 *
 * Используется для расписаний, графиков работы и планирования.
 */
export enum DayOfWeek {
  /** Воскресенье */
  SUNDAY,

  /** Понедельник */
  MONDAY,

  /** Вторник */
  TUESDAY,

  /** Среда */
  WEDNESDAY,

  /** Четверг */
  THURSDAY,

  /** Пятница */
  FRIDAY,

  /** Суббота */
  SATURDAY,
}
