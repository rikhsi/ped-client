/**
 * Квалификационные категории педагогических работников
 *
 * Используются для определения уровня
 * профессиональной квалификации педагога
 */
export enum PedagogueCategory {
  /** Категория «Специалист» (соответствие занимаемой должности) */
  SPECIALIST = 1,

  /** Вторая квалификационная категория */
  SECOND = 2,

  /** Первая квалификационная категория */
  FIRST = 3,

  /** Высшая квалификационная категория */
  HIGH = 4,
}

/**
 * Приоритет квалификационных категорий
 *
 * Используется для сортировки и сравнения
 * категорий от низшей к высшей
 */
export const CATEGORY_PRIORITY = [
  PedagogueCategory.SPECIALIST,
  PedagogueCategory.SECOND,
  PedagogueCategory.FIRST,
  PedagogueCategory.HIGH,
] as const;
