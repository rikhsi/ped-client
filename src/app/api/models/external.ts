/**
 * Список доступных внешних сервисов,
 * с которыми может быть связана запись справочника.
 */
export enum ExternalService {
  /** Тестовый сервис MNO */
  MNO_TEST = 1,

  /** Портал my.gov.uz */
  MY_GOV = 2,

  /** Система "Pedagog" */
  PEDAGOG = 3,

  /** ERP-система */
  ERP = 4,

  /** Сервис VIA */
  VIA = 5,

  /** Биллинг-система */
  BILLING = 6,
}

/**
 * Внешний идентификатор справочника.
 * Используется для связи сущности с данными во внешних сервисах.
 */
export interface ExternalItem {
  /** Внешний сервис, к которому относится идентификатор */
  service: ExternalService;

  /** Значение идентификатора в соответствующем сервисе */
  value: string;
}

/**
 * Данные, полученные или отправляемые во внешний сервис.
 */
export interface ExternalData {
  /** Сервис, из которого пришли или которому отправляются данные */
  fromService: ExternalService;

  /** Значение идентификатора в сервисе */
  value: string;
}
