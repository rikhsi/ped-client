/**
 * Универсальный элемент справочника.
 * Используется, когда нужно отобразить id + название.
 */
export interface HandbookItem {
  id: number; // Уникальный идентификатор
  name: string; // Название (может быть локализованным)
}

/**
 * Универсальный элемент для селектов / выпадающих списков.
 *
 * @typeParam T - тип значения (по умолчанию string).
 *   Может быть, например: string | number.
 */
export interface SelectItem<T = string> {
  /** Ключ для отображения (лейбл или перевод) */
  key: string;
  /** Значение, связанное с элементом */
  value: T;
}
