/**
 * Базовый результат ответа от API
 *
 * Используется как обёртка для всех
 * успешных и ошибочных ответов сервера
 */
export interface BaseResult<T> {
  /** Результат выполнения запроса */
  result: T;

  /** Информация об ошибке (если запрос завершился неуспешно) */
  error?: BaseError;
}

/**
 * Базовая модель ошибки API
 */
export interface BaseError {
  /** HTTP-статус или код ошибки */
  status_code: number;

  /** Сообщение об ошибке */
  message: string;
}

/**
 * Тип клиента
 *
 * Определяет, из какого приложения
 * был выполнен запрос
 */
export enum ClientType {
  /** Административное приложение */
  ADMIN = 1,

  /** Пользовательское приложение */
  USER = 2,
}
