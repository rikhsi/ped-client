/**
 * Диапазон зума карты.
 *
 * Используется для ограничения минимального и максимального уровня масштабирования.
 */
export interface ZoomRange {
  /** Минимальный уровень зума */
  min: number;

  /** Максимальный уровень зума */
  max: number;
}

/**
 * Режим округления или плавности изменения зума.
 *
 * - 'snap' — фиксированные шаги (например, 1, 2, 3)
 * - 'smooth' — плавное изменение масштаба
 * - 'auto' — выбирается автоматически в зависимости от карты
 */
export type ZoomRounding = 'snap' | 'smooth' | 'auto';

/**
 * Тема карты Яндекс (Yandex Maps).
 *
 * - 'light' — светлая тема
 * - 'dark' — тёмная тема
 */
export type YMapTheme = 'light' | 'dark';

/**
 * Центр карты.
 *
 * Двумерный массив: [широта, долгота]
 */
export type MapCenter = [number, number];

/**
 * Режим отображения карты.
 *
 * - 'raster' — растровая карта
 * - 'vector' — векторная карта
 * - 'auto' — автоматический выбор
 */
export type MapMode = 'raster' | 'vector' | 'auto';

/**
 * Контролы карты, которые можно включить или выключить.
 */
export type MapControl =
  | 'zoomControl'         // Контрол увеличения/уменьшения масштаба
  | 'typeSelector'        // Выбор типа карты (спутник/схема)
  | 'routePanelControl'   // Панель построения маршрута
  | 'routeEditor'         // Редактор маршрута на карте
  | 'mapTools'            // Дополнительные инструменты карты
  | 'rulerControl'        // Линейка для измерения расстояний
  | 'clusterer'           // Кластеризация меток
  | 'trafficControl'      // Контрол движения и пробок
  | 'searchControl'       // Поисковая панель
  | 'geolocationControl'  // Кнопка геолокации пользователя
  | 'fullscreenControl';  // Кнопка полноэкранного режима

/**
 * Поведение карты, которое можно включить или отключить.
 *
 * - 'drag' — перетаскивание карты мышью или пальцем
 * - 'scrollZoom' — масштабирование колесом мыши или жестом
 */
export type MapBehavior = 'drag' | 'scrollZoom';
